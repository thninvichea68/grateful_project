describe('cut stock and CDC lines', () => {
  async function item(qty: string, name = 'ELECTRONIC SCALE-30KG') {
    const [row] = await db
      .insert(cutStockItems)
      .values({
        clientId: basics.jr.id,
        lineNo: 4,
        declareRef: 'I-4',
        category: 'MACHINERY_EQUIPMENT',
        name,
        unit: 'SET',
        qty,
        unitPrice: '50',
      })
      .returning();
    return row!;
  }
  // The invoice item names the master-list item by its CDC No. (I-4, see item()).
  const importWith = (qty: string, extra: Record<string, unknown> = {}, declareNo = 'I 95001') =>
    exportShipment({
      direction: 'IMPORT',
      destinationCountryIso2: 'KH',
      originCountryIso2: 'CN',
      containers: [],
      loadType: 'LCL',
      invoices: [
        {
          invoiceNo: `CNG-${declareNo.replace(/\D/g, '')}`,
          lines: [{ cdcNo: 'I 4', pcs: qty, fobUnitPrice: '50', ...extra }],
        },
      ],
      declarations: [{ declareNo, declareDate: '2026-08-20' }],
    });
  const balance = async (id: string) =>
    (
      await request(app)
        .get(`/api/v1/cut-stock/${id}`)
        .set(await as('VIEWER'))
    ).body as { balance: string; condition: string; movements: unknown[] };

  it("an import invoice item reduces its CDC item's balance", async () => {
    const it1 = await item('10');
    const res = await request(app)
      .post('/api/v1/shipments')
      .set(await as('OPERATOR'))
      .send(importWith('6'));
    expect(res.status).toBe(201);
    expect(res.body.invoices[0].lines[0].cutStockItemId).toBe(it1.id);
    expect(await balance(it1.id)).toMatchObject({ balance: '4.000', condition: 'CHECK' }); // 40 % < 50 %
    expect((await balance(it1.id)).movements).toHaveLength(1);
  });

  it('blocks over-imports and lists the violations', async () => {
    const it1 = await item('10');
    const h = await as('OPERATOR');
    await request(app).post('/api/v1/shipments').set(h).send(importWith('6'));
    const res = await request(app)
      .post('/api/v1/shipments')
      .set(h)
      .send(importWith('5', {}, 'I 95002'));
    expect(res.status).toBe(422);
    expect(res.body.error.details).toEqual({
      rule: 'CUT_STOCK_OVER_IMPORT',
      violations: [
        {
          cutStockItemId: it1.id,
          itemName: 'ELECTRONIC SCALE-30KG',
          declareRef: 'I-4',
          balance: '4',
          requested: '5',
        },
      ],
    });
  });

  it('an override needs a Manager or Admin, and is recorded with who approved it', async () => {
    const it1 = await item('4');
    const body = importWith('5', {
      overrideReason: 'Customs approved extra unit (letter 12/08)',
    });
    expect(
      (
        await request(app)
          .post('/api/v1/shipments')
          .set(await as('OPERATOR'))
          .send(body)
      ).status,
    ).toBe(403);
    const ok = await request(app)
      .post('/api/v1/shipments')
      .set(await as('MANAGER'))
      .send(body);
    expect(ok.status).toBe(201);
    expect(ok.body.invoices[0].lines[0].overrideReason).toMatch(/Customs approved/);
    const b = await balance(it1.id);
    expect(b.balance).toBe('-1.000');
    expect(b.movements[0]).toMatchObject({ overrideBy: 'Test MANAGER' });
  });

  it("does not draw down another client's master list", async () => {
    const it1 = await item('10');
    const res = await request(app)
      .post('/api/v1/shipments')
      .set(await as('OPERATOR'))
      .send({ ...importWith('1'), clientId: basics.jyx.id });
    expect(res.status).toBe(201);
    expect(res.body.invoices[0].lines[0].cutStockItemId).not.toBe(it1.id);
    expect((await balance(it1.id)).balance).toBe('10.000');
  });

  it('declaration CDC lines no longer count', async () => {
    const it1 = await item('10');
    const res = await request(app)
      .post('/api/v1/shipments')
      .set(await as('OPERATOR'))
      .send({
        ...importWith('2'),
        declarations: [
          {
            declareNo: 'I 95009',
            declareDate: '2026-08-20',
            cdcLines: [{ cutStockItemId: it1.id, qty: '5' }],
          },
        ],
      });
    expect(res.status).toBe(201);
    expect((await balance(it1.id)).balance).toBe('8.000');
  });

  it('editing re-checks against the balance without double counting', async () => {
    const it1 = await item('10');
    const h = await as('OPERATOR');
    const created = (await request(app).post('/api/v1/shipments').set(h).send(importWith('6')))
      .body;
    const decl = created.declarations[0];
    const upd = await request(app)
      .put(`/api/v1/shipments/${created.id}`)
      .set(h)
      .send({
        ...importWith('10'),
        declarations: [{ id: decl.id, declareNo: decl.declareNo, declareDate: decl.declareDate }],
      });
    expect(upd.status).toBe(200);
    expect((await balance(it1.id)).balance).toBe('0.000');
  });

  it('deleting the shipment gives the quantity back', async () => {
    const it1 = await item('10');
    const created = (
      await request(app)
        .post('/api/v1/shipments')
        .set(await as('MANAGER'))
        .send(importWith('6'))
    ).body;
    await request(app)
      .delete(`/api/v1/shipments/${created.id}`)
      .set(await as('MANAGER'));
    expect((await balance(it1.id)).balance).toBe('10.000');
  });

  it('imports the real JR master list (dry run, apply, re-run) and exports it', async () => {
    const h = await as('OPERATOR');
    const file = fs.readFileSync(path.join(DATA, 'jr-cdc-master-list.xlsx'));
    const dry = await request(app)
      .post('/api/v1/cut-stock/import')
      .query({ clientId: basics.jr.id, dryRun: 'true' })
      .set(h)
      .attach('file', file, 'JR CDC MASTER LIST.xlsx');
    expect(dry.body).toMatchObject({ dryRun: true, created: 195, updated: 0, errors: [] });
    expect((await db.select({ n: sql<number>`count(*)::int` }).from(cutStockItems))[0]!.n).toBe(0);

    const applied = await request(app)
      .post('/api/v1/cut-stock/import')
      .query({ clientId: basics.jr.id, dryRun: 'false' })
      .set(h)
      .attach('file', file, 'JR CDC MASTER LIST.xlsx');
    expect(applied.body).toMatchObject({ created: 195 });
    const again = await request(app)
      .post('/api/v1/cut-stock/import')
      .query({ clientId: basics.jr.id, dryRun: 'false' })
      .set(h)
      .attach('file', file, 'JR CDC MASTER LIST.xlsx');
    expect(again.body).toMatchObject({ created: 0, updated: 0, unchanged: 195 });

    const list = await request(app)
      .get('/api/v1/cut-stock')
      .query({ clientId: basics.jr.id, condition: 'OVER' })
      .set(h);
    expect(list.body.summary).toMatchObject({ items: 195, overImported: 10 });
    expect(list.body.data).toHaveLength(10);
    const i10 = await db.select().from(cutStockItems).where(eq(cutStockItems.declareRef, 'I-10'));
    expect((await balance(i10[0]!.id)).balance).toBe('-24.000');

    const exp = await request(app)
      .get('/api/v1/cut-stock/export.xlsx')
      .query({ clientId: basics.jr.id })
      .set(h)
      .buffer(true)
      .parse((r, cb) => {
        const c: Buffer[] = [];
        r.on('data', (x: Buffer) => c.push(x));
        r.on('end', () => cb(null, Buffer.concat(c)));
      });
    expect(exp.status).toBe(200);
    expect(exp.headers['content-disposition']).toMatch(/JR-cdc-master-list/);
  });

  it('the picker returns balances for the shipment client', async () => {
    await item('10');
    const res = await request(app)
      .get('/api/v1/cut-stock/options')
      .query({ clientId: basics.jr.id, q: 'scale' })
      .set(await as('OPERATOR'));
    expect(res.body).toEqual([
      expect.objectContaining({ declareRef: 'I-4', balance: '10.000', unit: 'SET' }),
    ]);
  });
});

